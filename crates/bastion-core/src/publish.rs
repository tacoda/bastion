//! The publishing gate (F3): text that leaves for the world, such as a pull
//! request's, names no AI or tool as its author and carries no secret. A
//! finding names what it found, never the secret itself.

/// Prefixes that start a token, and what the token is.
const TOKENS: [(&str, &str); 8] = [
    ("ghp_", "a GitHub token"),
    ("gho_", "a GitHub token"),
    ("ghs_", "a GitHub token"),
    ("github_pat_", "a GitHub token"),
    ("sk-ant-", "an Anthropic key"),
    ("sk-", "an API key"),
    ("xoxb-", "a Slack token"),
    ("xoxp-", "a Slack token"),
];
/// How long the part after a prefix must be to read as a token.
const TOKEN_LEN: usize = 16;

/// Words that credit an author on their own, lowercased.
const CREDITS: [&str; 2] = ["co-authored-by:", "🤖"];
/// Words that credit an author when the line also names an AI tool.
const MADE: [&str; 3] = ["generated with", "generated by", "written by"];
/// AI tools, lowercased.
const TOOLS: [&str; 6] = ["claude", "chatgpt", "openai", "copilot", "gpt-", "an ai"];

/// Why `text` may not be published, one finding each; none means it may.
pub fn findings(text: &str) -> Vec<String> {
    let mut found: Vec<String> = text
        .lines()
        .filter(|l| attributes(l))
        .map(|l| format!("it credits an author: \"{}\"", l.trim()))
        .collect();
    found.extend(secrets(text));
    found
}

fn attributes(line: &str) -> bool {
    let line = line.to_lowercase();
    let has = |words: &[&str]| words.iter().any(|w| line.contains(w));
    has(&CREDITS) || (has(&MADE) && has(&TOOLS))
}

/// What secrets `text` holds, by kind, each named once.
pub fn secrets(text: &str) -> Vec<String> {
    let mut kinds: Vec<&str> = Vec::new();
    for word in text.split(|c: char| !in_token(c)) {
        match secret(word) {
            Some(kind) if !kinds.contains(&kind) => kinds.push(kind),
            _ => {}
        }
    }
    if text.contains("PRIVATE KEY-----") {
        kinds.push("a private key");
    }
    kinds.into_iter().map(|k| format!("it holds {k}")).collect()
}

/// Whether `c` can be part of a token.
fn in_token(c: char) -> bool {
    c.is_ascii_alphanumeric() || "_-".contains(c)
}

/// What secret one word is, if it is one.
fn secret(word: &str) -> Option<&'static str> {
    let token = TOKENS.iter().find_map(|(prefix, kind)| {
        let rest = word.strip_prefix(prefix)?;
        (rest.len() >= TOKEN_LEN).then_some(*kind)
    });
    let aws = word.len() == 20
        && word.starts_with("AKIA")
        && word
            .chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit());
    token.or(aws.then_some("an AWS access key"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn plain_text_may_be_published() {
        assert!(findings("Add multiply(a, b)\n\nCloses #12").is_empty());
        assert!(findings("Support the sk-ant- prefix in the key form").is_empty());
        assert!(findings("A report generated by cron each night").is_empty());
    }

    #[test]
    fn an_ai_credit_may_not_be_published() {
        let text = "Fix it\n\nCo-Authored-By: Claude <noreply@anthropic.com>";
        assert_eq!(findings(text).len(), 1);
        assert_eq!(findings("🤖 Generated with Claude Code").len(), 1);
    }

    #[test]
    fn a_secret_is_named_by_kind_never_by_value() {
        let key = format!("ghp_{}", "a1".repeat(18));
        let found = findings(&format!("token={key} and AKIAABCDEFGHIJKLMNOP"));
        assert_eq!(
            found,
            vec!["it holds a GitHub token", "it holds an AWS access key"]
        );
        assert!(found.iter().all(|f| !f.contains(&key)));
        assert_eq!(
            findings("-----BEGIN RSA PRIVATE KEY-----"),
            vec!["it holds a private key"]
        );
    }
}
